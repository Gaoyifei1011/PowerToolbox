namespace PowerToolbox.Extensions.DataType.Class
{
    /// <summary>
    /// 系统信息
    /// </summary>
    internal class SystemInformation
    {
        /// <summary>
        /// 主机名称
        /// </summary>
        internal string HostName { get; set; }

        /// <summary>
        /// 操作系统名称
        /// </summary>
        internal string OperatingSystemName { get; set; }

        /// <summary>
        /// 操作系统版本
        /// </summary>
        internal string OperatingSystemVersion { get; set; }

        /// <summary>
        /// 操作系统制造商
        /// </summary>
        internal string OperatingSystemManufacturer { get; set; }

        /// <summary>
        /// 产品 ID
        /// </summary>
        internal string ProductID { get; set; }

        /// <summary>
        /// 初始安装日期
        /// </summary>
        internal string FirstInstalledDate { get; set; }

        /// <summary>
        /// 系统启动时间
        /// </summary>
        internal string SystemBootTime { get; set; }

        /// <summary>
        /// 系统制造商
        /// </summary>
        internal string SystemManufacturer { get; set; }

        /// <summary>
        /// 系统型号
        /// </summary>
        internal string SystemModel { get; set; }

        /// <summary>
        /// 系统架构
        /// </summary>
        internal string SystemArchitecture { get; set; }

        /// <summary>
        /// 系统 SKU
        /// </summary>
        internal string SystemSKU { get; set; }

        /// <summary>
        /// 处理器
        /// </summary>
        internal string Processor { get; set; }

        /// <summary>
        /// BIOS 版本
        /// </summary>
        internal string BIOSVersion { get; set; }

        /// <summary>
        /// SMBIOS 版本
        /// </summary>
        internal string SMBIOSVersion { get; set; }

        /// <summary>
        /// 嵌入式控制器版本
        /// </summary>
        internal string EmbeddedControllerVersion { get; set; }

        /// <summary>
        /// BIOS 模式
        /// </summary>
        internal string BIOSMode { get; set; }

        /// <summary>
        /// 主板制造商
        /// </summary>
        internal string MainboardManufacturer { get; set; }

        /// <summary>
        /// 主板产品
        /// </summary>
        internal string MainboardProduct { get; set; }

        /// <summary>
        /// 主板版本
        /// </summary>
        internal string MainboardVersion { get; set; }

        /// <summary>
        /// Windows 目录
        /// </summary>
        internal string WindowsDirectory { get; set; }

        /// <summary>
        /// 系统目录
        /// </summary>
        internal string SystemDirectory { get; set; }

        /// <summary>
        /// 启动设备
        /// </summary>
        internal string BootDevice { get; set; }

        /// <summary>
        /// 区域设置
        /// </summary>
        internal string RegionSettings { get; set; }

        /// <summary>
        /// 时区
        /// </summary>
        internal string TimeZone { get; set; }

        /// <summary>
        /// 已安装的物理内存
        /// </summary>
        internal string InstalledPhysicalMemory { get; set; }

        /// <summary>
        /// 总物理内存
        /// </summary>
        internal string TotalPhysicalMemory { get; set; }

        /// <summary>
        /// 可用物理内存
        /// </summary>
        internal string AvailablePhysicalMemory { get; set; }

        /// <summary>
        /// 总的虚拟内存
        /// </summary>
        internal string TotalVirtualMemory { get; set; }

        /// <summary>
        /// 可用虚拟内存
        /// </summary>
        internal string AvailableVirtualMemory { get; set; }

        /// <summary>
        /// 页面文件位置
        /// </summary>
        internal string PageFilePosition { get; set; }

        /// <summary>
        /// 页面文件大小
        /// </summary>
        internal string PageFileSize { get; set; }
    }
}
